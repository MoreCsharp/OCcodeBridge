"""Local fake OpenCode Go upstream for the PlanBridge native acceptance run.

It speaks the two endpoints a PlanBridge request actually reaches:

    GET  /v1/models            OpenAI-style catalog
    POST /v1/chat/completions  non-stream JSON and streaming SSE

Every stream ends with a usage chunk carrying `opencode.allowance`, which is the
frame PlanBridge reads to show "counted against the plan" in its request log.
Nothing here talks to the internet, and the credentials it sees are the test
values generated by scripts/e2e-native.ps1 — never a real key.

Every request is appended to --capture as one JSON object per line so the
acceptance script can assert on the headers and the rewritten model id.
"""

import argparse
import json
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

# The one upstream model the script maps to the client-visible alias.
MODEL = "deepseek-v4.1-flash"
ANSWER = "FAKE-UPSTREAM-OK"

capture_lock = threading.Lock()
capture_path = ""


def record(entry):
    line = json.dumps(entry, ensure_ascii=False)
    with capture_lock:
        with open(capture_path, "a", encoding="utf-8") as handle:
            handle.write(line + "\n")
            handle.flush()


def usage_block():
    return {
        "prompt_tokens": 11,
        "completion_tokens": 7,
        "total_tokens": 18,
        "prompt_tokens_details": {"cached_tokens": 3},
    }


def allowance_block():
    # Shape PlanBridge reads as "this request counted against the plan".
    return {"used": 1.25, "limit": 30, "unit": "usd", "remaining": 28.75}


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):  # keep stderr for real failures only
        sys.stderr.write("fake-upstream: " + fmt % args + "\n")

    def _body(self):
        length = int(self.headers.get("Content-Length", "0"))
        return self.rfile.read(length) if length else b""

    def _send_json(self, status, payload):
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path.split("?")[0] == "/v1/models":
            self._send_json(200, {"data": [{
                "id": MODEL,
                "name": "DeepSeek V4.1 Flash",
                "context_length": 131072,
            }]})
            return
        self._send_json(404, {"error": {"message": "not found"}})

    def do_POST(self):
        if self.path.split("?")[0] != "/v1/chat/completions":
            self._send_json(404, {"error": {"message": "not found"}})
            return
        raw = self._body()
        try:
            payload = json.loads(raw.decode("utf-8")) if raw else {}
        except json.JSONDecodeError:
            self._send_json(400, {"error": {"message": "invalid JSON"}})
            return
        record({
            "path": self.path,
            "headers": {name: value for name, value in self.headers.items()},
            "body": payload,
        })
        if payload.get("stream") is True:
            self._send_stream(payload)
        else:
            self._send_completion(payload)

    def _send_completion(self, payload):
        self._send_json(200, {
            "id": "chatcmpl-fake",
            "object": "chat.completion",
            "created": int(time.time()),
            "model": payload.get("model") or MODEL,
            "choices": [{
                "index": 0,
                "message": {"role": "assistant", "content": ANSWER},
                "finish_reason": "stop",
            }],
            "usage": usage_block(),
            "opencode": {"allowance": allowance_block()},
        })

    def _send_stream(self, payload):
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "keep-alive")
        self.end_headers()

        def frame(obj):
            self.wfile.write(("data: " + json.dumps(obj, ensure_ascii=False) + "\n\n").encode("utf-8"))
            self.wfile.flush()

        model = payload.get("model") or MODEL
        base = {"id": "chatcmpl-fake", "object": "chat.completion.chunk",
                "created": int(time.time()), "model": model}
        frame({**base, "choices": [{"index": 0, "delta": {"role": "assistant", "content": ""}, "finish_reason": None}]})
        frame({**base, "choices": [{"index": 0, "delta": {"content": ANSWER}, "finish_reason": None}]})
        frame({**base, "choices": [{"index": 0, "delta": {}, "finish_reason": "stop"}]})
        # The terminal frame PlanBridge reads usage and the plan allowance from.
        frame({**base, "choices": [], "usage": usage_block(),
               "opencode": {"allowance": allowance_block()}})
        self.wfile.write(b"data: [DONE]\n\n")
        self.wfile.flush()


def main():
    global capture_path
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--capture", required=True)
    args = parser.parse_args()
    capture_path = args.capture
    open(capture_path, "w", encoding="utf-8").close()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"fake-opencode-upstream listening on 127.0.0.1:{args.port}", flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
